/**
 * 分段胶囊控件：三等分轨道 + 滑块，点击某段后滑块动画滑到该位置。
 */
@Composable
private fun <T> SegmentedPill(
    options: List<T>,
    selectedOption: T,
    onOptionSelected: (T) -> Unit,
    optionToString: @Composable (T) -> String,
    modifier: Modifier = Modifier,
) {
    val trackShape = RoundedCornerShape(50)
    val knobShape = RoundedCornerShape(50)
    Surface(
        modifier = modifier.height(32.dp),
        shape = trackShape,
        color = MaterialTheme.colorScheme.surfaceContainerHigh,
    ) {
        BoxWithConstraints(
            modifier = Modifier
                .fillMaxSize()
                .padding(3.dp),
        ) {
            val count = options.size.coerceAtLeast(1)
            val knobWidth = maxWidth / count
            val selectedIndex = options.indexOf(selectedOption).coerceAtLeast(0)
            val knobOffset by animateDpAsState(
                targetValue = knobWidth * selectedIndex,
                animationSpec = spring(dampingRatio = 0.8f, stiffness = 900f),
                label = "segmentedPillKnob",
            )

            Box(
                modifier = Modifier
                    .offset(x = knobOffset)
                    .width(knobWidth)
                    .fillMaxHeight()
                    .shadow(2.dp, knobShape)
                    .clip(knobShape)
                    .background(MaterialTheme.colorScheme.surfaceBright),
            )

            Row(modifier = Modifier.fillMaxSize()) {
                options.fastForEach { option ->
                    val selected = option == selectedOption
                    val contentColor by animateColorAsState(
                        targetValue = if (selected) {
                            MaterialTheme.colorScheme.onSurface
                        } else {
                            MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f)
                        },
                        animationSpec = tween(150),
                        label = "segmentedPillColor",
                    )
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .fillMaxHeight()
                            .clip(knobShape)
                            .clickable(
                                interactionSource = remember { MutableInteractionSource() },
                                indication = null,
                                onClick = { onOptionSelected(option) },
                            ),
                        contentAlignment = Alignment.Center,
                    ) {
                        Text(
                            text = optionToString(option),
                            style = MaterialTheme.typography.labelMedium,
                            color = contentColor,
                            maxLines = 1,
                        )
                    }
                }
            }
        }
    }
}
